MEMORY_FACTORS: Final = ("boundary_occupation", "initial_k", "translation_orbit")


def stage_bootstrap_seed(stage: Stage) -> int:
    """Read the stage's closed bootstrap allocation."""
    return STAGE_BOOTSTRAP_SEEDS[stage.value]


def memory_seed_census(
    stage: Stage,
    denominator: Denominator,
    clock_id: str,
    scientific_seeds: tuple[tuple[str, int], ...] | None,
) -> tuple[tuple[str, int], ...]:
    """Bind all three factor streams, independently of a caller clock label."""
    if scientific_seeds is not None and (
        not isinstance(scientific_seeds, tuple)
        or any(not isinstance(row, tuple) or len(row) != 2 for row in scientific_seeds)
        or tuple(factor for factor, _ in scientific_seeds) != MEMORY_FACTORS
        or any(type(seed) is not int or not 0 <= seed < 2**64 for _, seed in scientific_seeds)
        or len({seed for _, seed in scientific_seeds}) != 3
    ):
        raise ValueError("memory scientific seed census requires three declared 64-bit factor seeds")
    proposed = dict(scientific_seeds or ())
    result = []
    for factor in MEMORY_FACTORS:
        fixed = STAGE_MEMORY_SEEDS.get((stage.value, denominator.value, clock_id, factor))
        seed = proposed.get(factor, fixed)
        if seed is None:
            raise ValueError("caller clock requires an explicit memory scientific seed census")
        if fixed is not None and seed != fixed:
            raise ValueError("memory scientific seed differs from the fixed experiment allocation")
        result.append((factor, seed))
    return tuple(result)
