"""Complete frozen numerical inputs for the finite exposed preparation design.

These full seed commitments and ranks are scientific operands. Public root,
campaign and method labels never allocate a stream or select a population.
"""

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class PreparationScientificRootInputs:
    context: str
    index: int
    numerical_semantics_rank: int
    development_rank: int
    native_seed_sha256: tuple[str, ...]
    target_draw_sha256: tuple[str, ...]

    def __post_init__(self) -> None:
        if (
            self.context not in ("assembling", "prepared")
            or any(type(value) is not int or not 0 <= value < 64 for value in (
                self.index, self.numerical_semantics_rank, self.development_rank
            ))
            or not isinstance(self.native_seed_sha256, tuple)
            or len(self.native_seed_sha256) != 12
            or not isinstance(self.target_draw_sha256, tuple)
            or not self.target_draw_sha256
        ):
            raise ValueError("preparation scientific input geometry differs")
        for digest in (*self.native_seed_sha256, *self.target_draw_sha256):
            if not isinstance(digest, str) or len(digest) != 64 or any(
                value not in "0123456789abcdef" for value in digest
            ):
                raise ValueError("preparation scientific input requires a full lowercase SHA-256 commitment")

    def native_seed(self, *, purpose_index: int, bridge: bool) -> str:
        if type(purpose_index) is not int or not 0 <= purpose_index < 6 or type(bridge) is not bool:
            raise ValueError("preparation native purpose must name one of six independent numerical allocations")
        return self.native_seed_sha256[2 * purpose_index + int(bridge)]

    def target_draw(self, counter: int) -> str:
        if type(counter) is not int or not 0 <= counter < len(self.target_draw_sha256):
            raise ValueError("preparation target draw requires its complete frozen numerical census")
        return self.target_draw_sha256[counter]


